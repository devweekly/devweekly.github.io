-- CREATE OR REPLACE TABLE replaces any same-named table in this schema.
CREATE DATABASE IF NOT EXISTS SV_FINANCE_LAB;
CREATE SCHEMA IF NOT EXISTS SV_FINANCE_LAB.MART;

CREATE OR REPLACE TABLE SV_FINANCE_LAB.MART.DIM_PORTFOLIO (
  PORTFOLIO_ID VARCHAR(20) NOT NULL,
  PORTFOLIO_NAME VARCHAR(100) NOT NULL,
  INVESTMENT_STRATEGY VARCHAR(80) NOT NULL,
  BASE_CURRENCY VARCHAR(3) NOT NULL,
  RISK_PROFILE VARCHAR(30) NOT NULL,
  CONSTRAINT PK_DIM_PORTFOLIO PRIMARY KEY (PORTFOLIO_ID)
);

CREATE OR REPLACE TABLE SV_FINANCE_LAB.MART.DIM_SECURITY (
  SECURITY_ID VARCHAR(20) NOT NULL,
  TICKER VARCHAR(16) NOT NULL,
  SECURITY_NAME VARCHAR(160) NOT NULL,
  ASSET_CLASS VARCHAR(40) NOT NULL,
  SECTOR VARCHAR(80) NOT NULL,
  SECURITY_CURRENCY VARCHAR(3) NOT NULL,
  ISSUER_COUNTRY VARCHAR(2) NOT NULL,
  CONSTRAINT PK_DIM_SECURITY PRIMARY KEY (SECURITY_ID)
);

-- Grain: one aggregated row per PORTFOLIO_ID + SECURITY_ID + AS_OF_DATE.
-- PK declarations document the model; validate uniqueness in the data pipeline.
CREATE OR REPLACE TABLE SV_FINANCE_LAB.MART.FACT_POSITION_DAILY (
  PORTFOLIO_ID VARCHAR(20) NOT NULL,
  SECURITY_ID VARCHAR(20) NOT NULL,
  AS_OF_DATE DATE NOT NULL,
  QUANTITY NUMBER(24,8) NOT NULL,
  MARKET_VALUE_USD NUMBER(20,2) NOT NULL,
  COST_BASIS_USD NUMBER(20,2) NOT NULL,
  UNREALIZED_PNL_USD NUMBER(20,2) NOT NULL,
  ACCRUED_INTEREST_USD NUMBER(20,2) NOT NULL,
  CONSTRAINT PK_FACT_POSITION_DAILY PRIMARY KEY (PORTFOLIO_ID, SECURITY_ID, AS_OF_DATE)
);

