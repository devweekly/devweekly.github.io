-- Expected grain/key checks: zero rows from each duplicate check.
SELECT PORTFOLIO_ID, SECURITY_ID, AS_OF_DATE, COUNT(*) AS DUPLICATE_COUNT
FROM SV_FINANCE_LAB.MART.FACT_POSITION_DAILY
GROUP BY 1, 2, 3
HAVING COUNT(*) > 1;

SELECT PORTFOLIO_ID, COUNT(*) AS DUPLICATE_COUNT
FROM SV_FINANCE_LAB.MART.DIM_PORTFOLIO
GROUP BY 1
HAVING COUNT(*) > 1;

-- Expected orphan count: 0.
SELECT COUNT(*) AS ORPHAN_COUNT
FROM SV_FINANCE_LAB.MART.FACT_POSITION_DAILY p
LEFT JOIN SV_FINANCE_LAB.MART.DIM_PORTFOLIO f ON p.PORTFOLIO_ID = f.PORTFOLIO_ID
LEFT JOIN SV_FINANCE_LAB.MART.DIM_SECURITY s ON p.SECURITY_ID = s.SECURITY_ID
WHERE f.PORTFOLIO_ID IS NULL OR s.SECURITY_ID IS NULL;
