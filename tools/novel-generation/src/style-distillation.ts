export interface StyleSample {
  label: string;
  text: string;
}

/** Build an abstract, scene-aware style profile without imitating source passages. */
export function buildStyleDistillationPrompt(samples: StyleSample[]): string {
  return [
    "角色：文学风格分析与提炼编辑。请从用户提供且有权使用的作品样本中，提炼可供小说写作使用的抽象 Style Profile。",
    "目标是描述作品如何产生叙事效果，而不是复刻原文。禁止输出长段原文、标志性句子、可直接替换名词套用的句式模板，或要求模型模仿特定作者的独特表达。",
    "请优先观察：叙述视角与叙述距离、句子节奏如何变化、段落何时舒展或收紧、动作/环境/心理如何交织、对白如何承担关系动作、人物声音如何区分、意象与感官细节如何出现、情绪如何通过动作和留白抵达、信息何时解释何时延迟。",
    "输出一份可以直接保存为 style-profile.md 的 Markdown，包含：",
    "1. 全局叙事气质与最重要的 5-8 条抽象特征；",
    "2. 叙述视角、叙述距离、节奏、句法、段落和信息揭示的倾向；",
    "3. 场景级风格差异：对白、动作/打斗、群像、内心独白、环境、情感爆发等，只描述样本确实支持的类型；",
    "4. 人物声音的区分方式，不为人物编造固定口头禅；",
    "5. 有效写法与容易失效的反例，使用抽象描述或极短片段，不复刻独特表达；",
    "6. 写作时的使用原则：按场景灵活选择，不是配额、禁令或逐项验收表；原文特征与当前人物/场景冲突时，以当前作品的文学需要为准。",
    "不要把样本里偶然出现的现象误判为稳定风格。明确区分反复出现的特征与单次选择；证据不足时标注“样本不足”，不要编造。",
    "文学性、文笔、艺术风格高于一切统计特征。不得把句长、段落长度、对白比例或标点频率转成硬性目标。",
    ...samples.map((sample, index) => "样本 " + (index + 1) + "（" + sample.label + "）：\n" + sample.text)
  ].join("\n\n");
}
